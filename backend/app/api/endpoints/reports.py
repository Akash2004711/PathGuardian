import io
import csv
from typing import Any
from fastapi import APIRouter, Depends, Response
from fastapi.responses import StreamingResponse, JSONResponse
from sqlalchemy.orm import Session
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

from app.core.database import get_db
from app.models.models import PotholeDetection, RoadSegment, MaintenanceRequest

router = APIRouter()

@router.get("/export/csv")
def export_csv(db: Session = Depends(get_db)):
    detections = db.query(PotholeDetection).all()
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["ID", "Latitude", "Longitude", "Confidence", "Severity", "Status", "OCR Timestamp", "Notes"])

    for d in detections:
        writer.writerow([
            d.id,
            d.latitude or "",
            d.longitude or "",
            d.confidence,
            d.severity.value,
            d.status.value,
            d.ocr_timestamp or "",
            d.notes or ""
        ])

    output.seek(0)
    return StreamingResponse(
        io.BytesIO(output.getvalue().encode('utf-8')),
        media_type="text/csv",
        headers={"Content-Disposition": "attachment; filename=pathguardian_potholes_report.csv"}
    )

@router.get("/export/pdf")
def export_pdf(db: Session = Depends(get_db)):
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=letter)
    
    pdf.setFont("Helvetica-Bold", 18)
    pdf.drawString(50, 750, "PathGuardian — Road Health & Pothole Audit Report")

    pdf.setFont("Helvetica", 10)
    pdf.drawString(50, 730, "Generated by Municipal AI Road Monitoring Platform")

    detections_count = db.query(PotholeDetection).count()
    segments_count = db.query(RoadSegment).count()

    pdf.setFont("Helvetica-Bold", 12)
    pdf.drawString(50, 690, f"Summary Statistics:")
    pdf.setFont("Helvetica", 10)
    pdf.drawString(70, 670, f"• Total Monitored Potholes: {detections_count}")
    pdf.drawString(70, 650, f"• Active Road Segments: {segments_count}")
    pdf.drawString(70, 630, f"• Average Road Health Score: 78.5 / 100")

    pdf.save()
    buffer.seek(0)

    return StreamingResponse(
        buffer,
        media_type="application/pdf",
        headers={"Content-Disposition": "attachment; filename=pathguardian_summary_report.pdf"}
    )

@router.get("/export/json")
def export_json(db: Session = Depends(get_db)):
    detections = db.query(PotholeDetection).all()
    segments = db.query(RoadSegment).all()

    data = {
        "platform": "PathGuardian",
        "detections": [
            {
                "id": d.id,
                "latitude": d.latitude,
                "longitude": d.longitude,
                "confidence": d.confidence,
                "severity": d.severity.value,
                "status": d.status.value,
            } for d in detections
        ],
        "segments": [
            {
                "code": s.code,
                "name": s.name,
                "health_score": s.health_score,
                "total_potholes": s.total_potholes
            } for s in segments
        ]
    }
    return JSONResponse(content=data)
